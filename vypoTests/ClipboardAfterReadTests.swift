import Carbon.HIToolbox
import XCTest
@testable import vypo

/// The clipboard from before comes back after the target app has read the dictation, not on a guess (Fix 5).
@MainActor
final class ClipboardAfterReadTests: XCTestCase {
    private var pb: NSPasteboard!

    override func setUp() {
        pb = NSPasteboard(name: .init("vypo.test.\(UUID().uuidString)"))
        pb.clearContents()
        pb.setString("before", forType: .string)
    }

    override func tearDown() { pb.releaseGlobally() }

    private func spin(_ seconds: Double) { RunLoop.main.run(until: Date().addingTimeInterval(seconds)) }

    /// What another app does: reads from another thread while the main run loop answers the provider.
    private func readFromAnotherApp(_ types: [NSPasteboard.PasteboardType] = [.string]) -> String? {
        let done = expectation(description: "read")
        nonisolated(unsafe) var value: String?
        let pb = self.pb!
        DispatchQueue.global().async {
            for type in types { value = pb.string(forType: type) ?? value }
            done.fulfill()
        }
        wait(for: [done], timeout: 5)
        return value
    }

    // MARK: the rule

    func testDueWithoutAReadIsTheTimeout() {
        let p = RestorePolicy.standard
        let t = ContinuousClock.now
        let due = p.due(pasteAt: t, firstRead: nil, readBeforePaste: false)
        XCTAssertEqual(due.at, t + .seconds(5))
        XCTAssertEqual(due.reason, .timeout)
    }

    func testDueNeverBeforeQuarterSecondAfterPaste() {
        let p = RestorePolicy.standard
        let t = ContinuousClock.now
        // Read at once: still 250 ms after the paste (read + 150 ms would be earlier).
        let early = p.due(pasteAt: t, firstRead: t + .milliseconds(50), readBeforePaste: false)
        XCTAssertEqual(early.at, t + .milliseconds(250))
        XCTAssertEqual(early.reason, .afterRead)
    }

    func testDueWaitsAfterTheRead() {
        let p = RestorePolicy.standard
        let t = ContinuousClock.now
        // The incident: read 744 ms after the paste → back at 894 ms, not at 308 ms.
        let late = p.due(pasteAt: t, firstRead: t + .milliseconds(744), readBeforePaste: false)
        XCTAssertEqual(late.at, t + .milliseconds(894))
        // A read after the timeout is capped by it.
        let never = p.due(pasteAt: t, firstRead: t + .seconds(9), readBeforePaste: false)
        XCTAssertEqual(never.at, t + .seconds(5))
    }

    func testDueAfterAReadBeforeThePasteIsTheFallback() {
        let t = ContinuousClock.now
        let due = RestorePolicy.standard.due(pasteAt: t, firstRead: nil, readBeforePaste: true)
        XCTAssertEqual(due.at, t + .seconds(1))
        XCTAssertEqual(due.reason, .fallback)
    }

    // MARK: the item

    func testProviderReportsTheFirstReadAfterTheArmingOnly() throws {
        let item = DictationItem("dictated")
        item.write(to: pb)
        XCTAssertNil(item.reads.firstRead)
        item.arm()
        XCTAssertEqual(readFromAnotherApp(), "dictated")
        XCTAssertNotNil(item.reads.firstRead)
        XCTAssertFalse(item.reads.readBeforePaste)
    }

    func testAReadBeforeTheCommandVDoesNotCount() {
        let item = DictationItem("dictated")
        item.write(to: pb)
        XCTAssertEqual(readFromAnotherApp(), "dictated")   // a clipboard manager, say
        item.arm()
        XCTAssertNil(item.reads.firstRead)
        XCTAssertTrue(item.reads.readBeforePaste)
    }

    func testTheItemIsMarkedForClipboardManagers() {
        let item = DictationItem("dictated")
        item.write(to: pb)
        let types = pb.types ?? []
        XCTAssertTrue(types.contains(DictationItem.transientType))
        XCTAssertTrue(types.contains(DictationItem.autoGeneratedType))
        XCTAssertTrue(types.contains(.string))
        XCTAssertFalse(types.contains(.rtf))
    }

    /// Apps that ask for RTF or HTML first and fall back to text still get the text.
    func testAnAppAskingForSeveralTypesGetsText() {
        let item = DictationItem("dictated")
        item.write(to: pb)
        item.arm()
        XCTAssertNil(pb.data(forType: .rtf))
        XCTAssertNil(pb.data(forType: .html))
        XCTAssertEqual(readFromAnotherApp([.rtf, .html, .string]), "dictated")
    }

    // MARK: the restore

    private func restorer(_ policy: RestorePolicy) -> ClipboardRestorer {
        ClipboardRestorer(text: "dictated", saved: Paster.snapshot(pb), pasteboard: pb, policy: policy)
    }

    private let quick = RestorePolicy(afterPaste: .milliseconds(60), afterRead: .milliseconds(80),
                                      timeout: .milliseconds(400), fallback: .milliseconds(150))

    func testNotRestoredBeforeTheAppReadsIt() {
        let r = restorer(quick)
        r.pasted()
        spin(0.25)   // longer than afterPaste, shorter than the timeout: a slow app hasn't read yet
        XCTAssertTrue(r.stillOurs)
        XCTAssertEqual(readFromAnotherApp(), "dictated", "the slow app still gets the dictation")
        spin(0.3)
        XCTAssertEqual(pb.string(forType: .string), "before")
        XCTAssertFalse(r.isWaiting)
    }

    func testRestoredAfterTheReadPlusDelay() {
        let r = restorer(quick)
        r.pasted()
        spin(0.1)
        _ = readFromAnotherApp()
        spin(0.02)
        XCTAssertTrue(r.stillOurs, "not 20 ms after the read")
        spin(0.2)
        XCTAssertEqual(pb.string(forType: .string), "before")
    }

    func testRestoredOnTimeoutWhenNothingReads() {
        let r = restorer(quick)
        r.pasted()
        spin(0.3)
        XCTAssertTrue(r.stillOurs)
        spin(0.35)
        XCTAssertEqual(pb.string(forType: .string), "before")
    }

    func testRestoredAfterTheFallbackWhenReadEarly() {
        let r = restorer(quick)
        XCTAssertEqual(readFromAnotherApp(), "dictated")
        r.pasted()
        spin(0.08)
        XCTAssertTrue(r.stillOurs)
        spin(0.2)
        XCTAssertEqual(pb.string(forType: .string), "before")
    }

    func testSomethingCopiedMeanwhileStaysAndAbandonRestoresNothing() {
        let r = restorer(quick)
        r.pasted()
        _ = readFromAnotherApp()
        pb.clearContents()
        pb.setString("copied by you", forType: .string)
        spin(0.3)
        XCTAssertEqual(pb.string(forType: .string), "copied by you")

        let r2 = restorer(quick)
        r2.pasted()
        r2.abandon()
        spin(0.7)
        XCTAssertEqual(pb.string(forType: .string), "dictated", "an abandoned restore does nothing")
    }

    func testKeepThenYourPasteRestoresAfterTheRead() {
        // Through the real entry point on the test pasteboard is not possible (it uses the general one),
        // so the keeper covers the same path: keep → your ⌘V → read → restore.
        let keeper = ClipboardKeeper(pasteboard: pb, policy: quick)
        keeper.keep("dictated", restoreAfterPaste: true, paste: false)
        keeper.userPasted()
        spin(0.1)
        XCTAssertEqual(readFromAnotherApp(), "dictated")
        spin(0.3)
        XCTAssertEqual(pb.string(forType: .string), "before")
        XCTAssertFalse(keeper.isHolding)
    }

    func testASecondDictationWhileWaitingKeepsTheFirstClipboard() {
        let keeper = ClipboardKeeper(pasteboard: pb, policy: quick)
        keeper.keep("one", restoreAfterPaste: true, paste: false)
        keeper.userPasted()
        keeper.keep("two", restoreAfterPaste: true, paste: false)
        keeper.settle()
        XCTAssertEqual(pb.string(forType: .string), "before")
    }
}
