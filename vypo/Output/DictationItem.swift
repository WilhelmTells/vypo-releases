import AppKit

/// When the clipboard from before may come back after a dictation was pasted (§12). The app tells us it read
/// the dictation by asking the promised item for its text; a fixed wait is only the fallback.
struct RestorePolicy: Sendable {
    /// Earliest restore after the ⌘V, whatever the app did.
    var afterPaste: Duration = .milliseconds(250)
    /// How long after the first read the app is given to finish with the text.
    var afterRead: Duration = .milliseconds(150)
    /// Latest restore after the ⌘V, when nothing ever read the dictation.
    var timeout: Duration = .seconds(5)
    /// When the read can't be trusted (something read the item before the ⌘V, and the pasteboard answers
    /// a second read from its own copy): restore this long after the ⌘V, as before.
    var fallback: Duration = .seconds(1)

    static let standard = RestorePolicy()
    /// For tests that don't want to wait.
    static let immediate = RestorePolicy(afterPaste: .zero, afterRead: .zero, timeout: .zero, fallback: .zero)

    enum Reason: Equatable { case afterRead, timeout, fallback }

    /// The moment the clipboard may come back, and why then. `firstRead` is the first time the item was asked
    /// for its text after the ⌘V; `readBeforePaste` is whether it was asked earlier.
    func due(pasteAt: ContinuousClock.Instant, firstRead: ContinuousClock.Instant?, readBeforePaste: Bool)
        -> (at: ContinuousClock.Instant, reason: Reason)
    {
        if readBeforePaste { return (pasteAt + max(fallback, afterPaste), .fallback) }
        guard let firstRead else { return (pasteAt + timeout, .timeout) }
        let at = max(pasteAt + afterPaste, firstRead + afterRead)
        return (min(at, pasteAt + max(timeout, afterPaste)), .afterRead)
    }
}

/// The dictation as a promised pasteboard item: the text is only handed over when an app asks for it, and
/// that moment is recorded. Only `.string` is promised; the rest of the types are markers for clipboard managers.
final class DictationItem: NSObject, NSPasteboardItemDataProvider, @unchecked Sendable {
    /// `org.nspasteboard.org` convention: clipboard managers skip items marked like this.
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private let text: String
    private let lock = NSLock()
    private var armedAt: ContinuousClock.Instant?
    private var firstRead: ContinuousClock.Instant?
    private var earlyRead = false

    init(_ text: String) { self.text = text }

    /// Writes the dictation to `pasteboard`, kept on this Mac only. Returns the change count of that write.
    /// The pasteboard holds the item's provider weakly, so the caller must keep the `DictationItem` alive
    /// until the clipboard is restored.
    @discardableResult
    func write(to pasteboard: NSPasteboard) -> Int {
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        item.setDataProvider(self, forTypes: [.string])
        item.setData(Data(), forType: Self.transientType)
        item.setData(Data(), forType: Self.autoGeneratedType)
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    /// Called right before the ⌘V is posted: reads from now on count as the app's.
    func arm(at now: ContinuousClock.Instant = .now) {
        lock.lock(); defer { lock.unlock() }
        armedAt = now
    }

    struct Reads { var firstRead: ContinuousClock.Instant?; var readBeforePaste: Bool; var armed: ContinuousClock.Instant? }

    var reads: Reads {
        lock.lock(); defer { lock.unlock() }
        return Reads(firstRead: firstRead, readBeforePaste: earlyRead, armed: armedAt)
    }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        let now = ContinuousClock.now
        lock.lock()
        if armedAt == nil { earlyRead = true } else if firstRead == nil { firstRead = now }
        lock.unlock()
        item.setString(text, forType: type)
    }
}

/// Holds a dictation on the pasteboard and puts the clipboard from before back once the app has read it.
@MainActor
final class ClipboardRestorer {
    let saved: Paster.Snapshot
    let item: DictationItem
    let change: Int
    let policy: RestorePolicy
    let app: String
    private let pasteboard: NSPasteboard
    private var pasteAt: ContinuousClock.Instant?
    private var task: Task<Void, Never>?
    /// Why the restore ran, once it has (nil for a restore before the next dictation, or not yet).
    private(set) var finishReason: RestorePolicy.Reason?
    /// When the ⌘V was posted the second time (Try it only); the timeout counts from then, so the retry can still be read.
    private(set) var retriedAt: ContinuousClock.Instant?

    /// Writes `text` to the pasteboard; `saved` is the clipboard from before.
    init(text: String, saved: Paster.Snapshot, pasteboard: NSPasteboard, policy: RestorePolicy) {
        self.saved = saved
        self.pasteboard = pasteboard
        self.policy = policy
        item = DictationItem(text)
        change = item.write(to: pasteboard)
        app = Paster.frontBundleID()
    }

    var stillOurs: Bool { pasteboard.changeCount == change }
    /// Time since the first ⌘V, and whether the app has asked for the text since then.
    var sincePaste: Duration { pasteAt.map { ContinuousClock.now - $0 } ?? .zero }
    var wasRead: Bool { item.reads.firstRead != nil }

    /// Posts the ⌘V once more and gives the timeout a new start. Only if still waiting with our item on the pasteboard.
    @discardableResult
    func repaste(post: () -> Void) -> Bool {
        guard isWaiting, stillOurs, retriedAt == nil else { return false }
        retriedAt = .now
        post()
        return true
    }
    var isWaiting: Bool { task != nil }

    /// The ⌘V is about to be posted (by vypo or by you): from now on a read counts, and the restore is timed.
    func pasted(then done: (@MainActor () -> Void)? = nil) {
        let start = ContinuousClock.now
        pasteAt = start
        item.arm(at: start)
        let app = Paster.frontBundleID()
        task = Task { [self] in
            var due = policy.due(pasteAt: start, firstRead: nil, readBeforePaste: false)
            while !Task.isCancelled {
                let reads = item.reads
                due = policy.due(pasteAt: retriedAt ?? start, firstRead: reads.firstRead, readBeforePaste: reads.readBeforePaste)
                let now = ContinuousClock.now
                if now >= due.at { break }
                try? await Task.sleep(for: min(due.at - now, .milliseconds(10)))
            }
            guard !Task.isCancelled else { return }
            finish(start: start, reason: due.reason, app: app)
            done?()
        }
    }

    /// A newer dictation took the pasteboard over: stop waiting, restore nothing.
    func abandon() {
        task?.cancel()
        task = nil
    }

    /// Now: before the next dictation, the clipboard from before comes back at once (if still ours).
    func settle() {
        task?.cancel()
        task = nil
        finish(start: pasteAt ?? .now, reason: nil, app: app)
    }

    private func finish(start: ContinuousClock.Instant, reason: RestorePolicy.Reason?, app: String) {
        task = nil
        finishReason = reason
        let untouched = stillOurs
        if untouched { Paster.restore(saved, pasteboard) }
        let reads = item.reads
        Paster.logRestore(restored: untouched, reason: reason, start: start, firstRead: reads.firstRead,
                          readBeforePaste: reads.readBeforePaste, app: app, snapshot: saved)
    }
}
